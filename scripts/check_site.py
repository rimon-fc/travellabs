#!/usr/bin/env python3
"""Validate the published artifact, including a GitHub Pages project prefix."""
from pathlib import Path
from html.parser import HTMLParser
from urllib.parse import urlsplit, urljoin, unquote
from collections import Counter
import json
import re
from build_site import ROOT, OUTPUT, BUSINESSES, PLAN, SOURCE, BRIEF

PREFIX = '/travellabs/'
HOST = 'https://rimon-fc.github.io'
errors = []
cache = {}

class Page(HTMLParser):
    def __init__(self, text):
        super().__init__()
        self.ids = []
        self.refs = []
        self.viewport = False
        self.feed(text)
    def handle_starttag(self, tag, attrs):
        attrs = dict(attrs)
        if 'id' in attrs:
            self.ids.append(attrs['id'])
        if tag == 'meta' and attrs.get('name') == 'viewport':
            self.viewport = 'width=device-width' in attrs.get('content','')
        for name in ('href', 'src', 'poster', 'action', 'data-url'):
            if name in attrs:
                self.refs.append(attrs[name])
    def handle_startendtag(self, tag, attrs):
        self.handle_starttag(tag, attrs)


def parse(path):
    if path not in cache:
        cache[path] = Page(path.read_text())
    return cache[path]


def check_ref(path, ref, fragments=True):
    if not ref or ref.startswith(('data:', 'mailto:', 'tel:', 'javascript:')):
        return
    split = urlsplit(ref)
    if split.netloc or split.scheme:
        return
    relative = path.relative_to(OUTPUT).as_posix()
    full = urlsplit(urljoin(HOST + PREFIX + relative, ref))
    if not full.path.startswith(PREFIX):
        errors.append(f'{relative}: escapes project prefix: {ref}')
        return
    target = OUTPUT / unquote(full.path[len(PREFIX):])
    if target.is_dir():
        target = target / 'index.html'
    if not target.is_file():
        errors.append(f'{relative}: missing local resource: {ref}')
        return
    if fragments and full.fragment and target.suffix == '.html':
        if unquote(full.fragment) not in parse(target).ids:
            errors.append(f'{relative}: missing fragment: {ref}')


def check():
    assert OUTPUT.exists(), 'Build the site first.'
    for path in sorted(OUTPUT.rglob('*')):
        if not path.is_file():
            continue
        if path.name.lower().startswith('readme') or path.name == '.DS_Store':
            errors.append(f'Unwanted file: {path.relative_to(OUTPUT)}')
        if path.suffix == '.html':
            page = parse(path)
            if not page.viewport:
                errors.append(f'{path.relative_to(OUTPUT)}: missing responsive viewport')
            for id, count in Counter(page.ids).items():
                if count > 1:
                    errors.append(f'{path.relative_to(OUTPUT)}: duplicate ID {id}')
            for ref in page.refs:
                check_ref(path, ref)
            if 'file:///Users/' in path.read_text():
                errors.append(f'{path.relative_to(OUTPUT)}: local machine link')
        if path.suffix in ('.css', '.html', '.svg'):
            for match in re.finditer(r'''url\(\s*("[^"]*"|'[^']*'|[^)]*)\s*\)''', path.read_text()):
                value = match[1].strip()
                ref = value[1:-1] if value.startswith(('"', "'")) else value
                check_ref(path, ref, fragments=False)
    for slug, name, _ in BUSINESSES:
        page = OUTPUT / 'startups' / slug / 'index.html'
        alias = OUTPUT / 'startups' / (slug + '.html')
        if not page.exists() or not alias.exists():
            errors.append(f'Missing public routes for {name}')
        if page.exists() and 'Built by Rimon R for Travellabs' not in page.read_text():
            errors.append(f'{name}: missing author credit')
    assert (SOURCE / BRIEF).exists(), 'Original brief source filename must be retained.'
    assert (OUTPUT / PLAN).exists(), 'Friendly launch-plan route is required.'
    gallery = (OUTPUT / 'businesses.html').read_text()
    for slug, _, _ in BUSINESSES:
        if f'href="startups/{slug}/"' not in gallery:
            errors.append(f'Business gallery does not point to {slug}')
    mcpx = OUTPUT / 'startups/mcpx-travel'
    assert (mcpx/'startups.html').exists() and (OUTPUT/'startups.html').exists(), 'Separate mcpx and umbrella startup pages must coexist.'
    # These links are generated by the mcpx script, relative to its document.
    script = (mcpx/'assets/site.js').read_text()
    for name in set(re.findall(r'[\"\']([a-z-]+\.html)(?:#[\w-]+)?[\"\']', script)):
        if not (mcpx/name).exists():
            errors.append(f'mcpx generated navigation: missing {name}')
    # Ensure the source bundle itself follows the no-README requirement.
    assert not [p for p in ROOT.rglob('*') if p.is_file() and p.name.lower().startswith('readme') and '.git' not in p.parts]
    report = {'html_pages':len(cache), 'businesses':len(BUSINESSES), 'prefix':PREFIX,
              'source_filename_preserved':True, 'errors':errors}
    print(json.dumps(report,indent=2))
    if errors:
        raise SystemExit(1)

if __name__ == '__main__':
    check()
